const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { spawnSync } = require('node:child_process')

test('Action verification rejects stale, extra and linked files in the distributable bundle', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'workspace-action-test-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  await fs.mkdir(path.join(root, 'scripts'))
  await fs.copyFile(path.join(__dirname, '../scripts/build-action.mjs'), path.join(root, 'scripts/build-action.mjs'))
  await fs.cp(path.join(__dirname, '../sandbox-actions'), path.join(root, 'sandbox-actions'), { recursive: true })
  const run = (...args) => spawnSync(process.execPath, [path.join(root, 'scripts/build-action.mjs'), ...args], { encoding: 'utf8' })
  assert.equal(run().status, 0)
  assert.equal(run('--verify-package', root).status, 0)
  const runner = path.join(root, 'dist/sandbox-actions/bundle/runner.mjs')
  await fs.appendFile(runner, '\n// stale')
  assert.notEqual(run('--verify').status, 0)
  assert.equal(run().status, 0)
  const extra = path.join(root, 'dist/sandbox-actions/bundle/extra.mjs')
  await fs.writeFile(extra, 'extra')
  assert.notEqual(run('--verify-package', root).status, 0)
  await fs.unlink(extra)
  await fs.unlink(runner)
  await fs.symlink(path.join(root, 'sandbox-actions/runner.mjs'), runner)
  assert.notEqual(run('--verify-package', root).status, 0)
  await fs.rm(path.join(root, 'dist/sandbox-actions/bundle'), { recursive: true })
  await fs.symlink(path.join(root, 'sandbox-actions'), path.join(root, 'dist/sandbox-actions/bundle'))
  assert.notEqual(run('--verify-package', root).status, 0)
  await fs.symlink(path.join(root, 'sandbox-actions/runner.mjs'), path.join(root, 'sandbox-actions/linked.mjs'))
  assert.notEqual(run().status, 0)
})
