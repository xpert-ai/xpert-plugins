const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { spawnSync } = require('node:child_process')

test('HTML Action verifier rejects stale bytes, extra files and linked bundle entries', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'dashboard-action-test-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const action = path.join(root, 'dist/sandbox-actions'), bundle = path.join(action, 'bundle')
  await fs.cp(path.join(__dirname, '../dist/sandbox-actions'), action, { recursive: true })
  const verify = () => spawnSync(process.execPath, [path.join(__dirname, '../scripts/build-action.mjs'), '--verify-package', root], { encoding: 'utf8' })
  const valid = verify(); assert.equal(valid.status, 0, valid.stderr)
  const runner = path.join(bundle, 'runner.mjs'), original = await fs.readFile(runner)
  await fs.appendFile(runner, '\n// stale')
  assert.match(verify().stderr, /Stale HTML validation action/)
  await fs.writeFile(runner, original)
  const extra = path.join(bundle, 'extra.mjs'); await fs.writeFile(extra, 'extra')
  assert.match(verify().stderr, /file list differs/)
  await fs.unlink(extra); await fs.unlink(runner)
  await fs.symlink(path.join(__dirname, '../sandbox-actions/runner.mjs'), runner)
  assert.match(verify().stderr, /Invalid Action bundle file/)
  await fs.unlink(runner); await fs.writeFile(runner, original)
  const manifest = path.join(action, 'action.json'); await fs.unlink(manifest)
  await fs.symlink(path.join(__dirname, '../dist/sandbox-actions/action.json'), manifest)
  assert.match(verify().stderr, /Invalid Action manifest/)
  await fs.rm(bundle, { recursive: true }); await fs.symlink(path.join(__dirname, '../dist/sandbox-actions/bundle'), bundle)
  assert.match(verify().stderr, /Invalid Action bundle directory/)
})
