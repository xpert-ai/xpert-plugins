const { test } = require('node:test'), assert = require('node:assert/strict')
const { LibraryDirectoryService } = require('../dist/lib/library/directory.service')
const { directoryQuerySchema } = require('../dist/lib/library/directory-contract')
const { encodePackage, decodePackage } = require('../dist/lib/library/archive')
const { buildExplorePackage } = require('../scripts/explore-package.cjs')
const { buildHotelPackage } = require('../scripts/hotel-package.cjs')
const { reference } = require('../dist/lib/library/archive')
const blueprints = require('../dist/lib/library/catalog-blueprints.json')
test('bounded directory validates filters and selects only one page before release lookup',async()=>{
  const lookedUp=[],directory=new LibraryDirectoryService({actor:async()=>({}),matchOwned:async(_,ids)=>{lookedUp.push(ids);return []}})
  const result=await directory.list({}, {kind:'visual-theme',page:2,pageSize:12,locale:'zh-Hant'})
  assert.equal(result.total,43);assert.equal(result.items.length,12);assert.equal(lookedUp[0].length,12)
  assert.ok(result.items.every(item=>item.state==='planned'&&item.releaseId===null))
  assert.equal((await directory.list({}, {kind:'component',category:'charts',pageSize:50})).total,20)
  assert.equal(directoryQuerySchema.safeParse({kind:'example-task',pageSize:51}).success,false)
  assert.equal(directoryQuerySchema.safeParse({kind:'example-task',search:'a'.repeat(101)}).success,false)
  assert.equal(directoryQuerySchema.safeParse({kind:'example-task',audience:'official'}).success,false)
  // Reject malformed persisted navigation before mounting the directory, rather than throwing in render.
  assert.equal(require('../dist/lib/library.schema').libraryQuerySchema.safeParse({parameters:{catalogPage:100001}}).success,false)
})
test('standalone ten-task package is deterministic, complete and does not mutate the old hotel version',()=>{
  const content=buildExplorePackage(),zip=encodePackage(content),roundtrip=decodePackage(zip)
  assert.deepEqual(encodePackage(buildExplorePackage()),zip)
  assert.equal(roundtrip.roots.length,10);assert.equal(roundtrip.resources.length,15);assert.equal(roundtrip.blobs.size,14)
  const tasks=roundtrip.resources.filter(item=>item.kind==='example-task')
  for(const task of tasks){
    assert.ok(blueprints.some(item=>item.logicalId===task.logicalId&&item.kind===task.kind))
    assert.ok(task.presentation.coverAssetId);assert.ok(task.content.dataRequirement)
    assert.equal(task.content.execution.mode,task.catalogKey==='hotel-operations'?'template':'agent')
  }
  for(const dataset of roundtrip.resources.filter(item=>item.kind==='public-dataset'))assert.ok(dataset.content.columns.every(column=>column.role))
  const old=buildHotelPackage(),hotel=tasks.find(item=>item.catalogKey==='hotel-operations')
  assert.equal(hotel.version,'2.1.0')
  for(const document of old.resources.filter(item=>item.kind!=='example-task'))assert.deepEqual(reference(document),reference(roundtrip.resources.find(item=>item.logicalId===document.logicalId)))
})
