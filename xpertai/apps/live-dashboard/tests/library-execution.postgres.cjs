require('reflect-metadata')
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { DataSource } = require('typeorm')
const { entities } = require('./library-v2-fixture.cjs')
const { executionFixture } = require('./library-execution-fixture.cjs')
const { encodePackage } = require('../dist/lib/library/archive.js')
const { DashboardMiddleware } = require('../dist/lib/middleware.js')
const url = process.env.LIVE_DASHBOARD_LIBRARY_TEST_DATABASE_URL
test('V2 template execution with PostgreSQL and real Dashboard save services', { skip: !url }, async t => {
  const schema = `execution_test_${randomUUID().replaceAll('-', '')}`
  const db = new DataSource({ type: 'postgres', url, schema, entities: entities.LIBRARY_V2_ENTITIES, synchronize: false, extra: { options: `-c search_path=${schema},public` } })
  await db.initialize(); await db.query(`CREATE SCHEMA "${schema}"`); await db.synchronize()
  t.after(async () => { await db.query(`DROP SCHEMA "${schema}" CASCADE`); await db.destroy() })

  await t.test('prepare is repeatable and copies prompt, skills and recipe without creating a Dashboard', async () => {
    const f = await executionFixture(db), requestId = randomUUID()
    const draft = await f.tasks.prepare(f.context, f.task.releaseId, requestId)
    assert.deepEqual(await f.tasks.prepare(f.context, f.task.releaseId, requestId), draft)
    assert.match(draft.text, /合成示例/); assert.deepEqual(draft.skillNames, ['live-dashboard']); assert.equal(draft.workspaceFiles.length, 2)
    const recipe = JSON.parse(f.runtime.state.files.get(draft.workspaceFiles[1].path).toString())
    assert.equal(recipe.action.tool, 'dashboard_instantiate_template'); assert.equal(recipe.action.arguments.requestId, requestId)
    assert.equal(f.host.artifacts.size, 0); assert.equal(f.jobs.size, 0)
    await assert.rejects(f.tasks.prepare({ ...f.context, readonly: true }, f.task.releaseId, requestId), /ACCESS_DENIED/)
  })
  await t.test('template recipe saves through the existing queue and preserves portable template provenance', async () => {
    const f = await executionFixture(db), input = f.request(), pending = await f.execution.instantiate(f.context, input)
    assert.equal(pending.state, 'queued'); assert.equal(pending.dashboard, undefined)
    const duplicate = await f.make().instantiate(f.context, input)
    assert.equal(duplicate.executionId, pending.executionId); assert.equal(duplicate.requestId, pending.requestId); assert.equal(f.jobs.size, 1)
    await f.run(pending)
    const result = await f.execution.status(f.context, pending.executionId)
    assert.equal(result.state, 'succeeded'); assert.equal(result.dashboard.draftRevision, 1)
    const saved = await f.host.service.open(f.context, result.dashboard.artifactId)
    assert.equal(saved.manifest.templateOrigin.template.version, '1.0.0')
    assert.equal(saved.manifest.templateOrigin.inputs[0].source.type, 'library')
    assert.deepEqual(saved.manifest.bindings[0].output.grain, ['month'])
    assert.match(saved.manifest.presentation.html, /id="xpert-template-context"/)
    assert.ok(!saved.manifest.presentation.html.includes('2026-01'))
    assert.deepEqual(await f.make().instantiate(f.context, input), result)
  })
  await t.test('concurrent submissions create one execution and changed intent/context is denied', async () => {
    const f = await executionFixture(db), input = f.request()
    const [a, b] = await Promise.all([f.execution.instantiate(f.context, input), f.execution.instantiate(f.context, input)])
    assert.equal(a.requestId, b.requestId); assert.equal(f.jobs.size, 1)
    await assert.rejects(f.execution.instantiate(f.context, { ...input, title: 'changed' }), /EXECUTION_CONFLICT/)
    await assert.rejects(f.execution.instantiate({ ...f.context, hostId: randomUUID() }, input), /EXECUTION_DENIED/)
    await assert.rejects(f.execution.status({ ...f.context, userId: randomUUID() }, a.executionId), /EXECUTION_DENIED/)
  })
  await t.test('queue submission interruption recovers its frozen manifest without re-registering data', async () => {
    const f = await executionFixture(db), input = f.request(); f.failSubmit()
    await assert.rejects(f.execution.instantiate(f.context, input), /ENQUEUE_INTERRUPTED/)
    assert.equal(f.definitions.size, 1)
    const pending = await f.make().instantiate(f.context, input)
    assert.equal(f.definitions.size, 1); assert.equal(f.jobs.size, 1)
    await f.run(pending); assert.equal((await f.execution.status(f.context, pending.executionId)).state, 'succeeded')
  })
  await t.test('invalid input slots do not reserve the creation intent or prevent correction', async () => {
    const f = await executionFixture(db), input = f.request()
    const resolved = await f.resolution.template(f.context, input)
    await assert.rejects(f.execution.instantiate(f.context, {
      ...input, inputs: [{ ...resolved.inputs[0], slot: 'unknown_slot' }]
    }), /TEMPLATE_INPUTS_REQUIRED/)
    assert.equal(await db.getRepository(entities.LibraryExecutionRecord).countBy({ requestId: input.requestId }), 0)
    assert.equal(f.jobs.size, 0)
    const pending = await f.execution.instantiate(f.context, input)
    await f.run(pending)
    assert.equal((await f.execution.status(f.context, pending.executionId)).state, 'succeeded')
  })
  await t.test('retry rechecks an explicitly selected dataset revision before submitting a prepared manifest', async () => {
    const f = await executionFixture(db), input = f.request(), resolved = await f.resolution.template(f.context, input)
    const item = resolved.inputs[0], bound = await f.bindings.bind(f.context, item, resolved.template.content.inputSlots[0], randomUUID())
    const id = randomUUID(), record = { artifactId: id, revision: 1, definition: { binding: bound.binding, controls: {} } }
    f.custom.set(id, record)
    input.inputs = [{ ...item, source: { type: 'dataset', artifactId: id, revision: 1 } }]
    f.failSubmit(); await assert.rejects(f.execution.instantiate(f.context, input), /ENQUEUE_INTERRUPTED/)
    record.revision = 2
    await assert.rejects(f.make().instantiate(f.context, input), /DATASET_CONFLICT/)
    assert.equal(f.jobs.size, 0)
    f.custom.delete(id)
    await assert.rejects(f.make().instantiate(f.context, input), /DATASET_DENIED/)
  })
  await t.test('exported resource package imports into another identity with new local IDs and the same template', async () => {
    const original = await executionFixture(db)
    const exported = encodePackage(await original.catalog.exportPackage(original.context, [original.task.releaseId]))
    const target = await executionFixture(db, exported)
    assert.notEqual(target.context.userId, original.context.userId); assert.notEqual(target.task.releaseId, original.task.releaseId)
    const pending = await target.execution.instantiate(target.context, target.request())
    await target.run(pending)
    const saved = await target.execution.status(target.context, pending.executionId)
    const instance = await target.host.service.open(target.context, saved.dashboard.artifactId)
    const expected = await original.resolution.template(original.context, original.request())
    assert.equal(instance.manifest.templateOrigin.template.logicalId, expected.template.logicalId)
    assert.equal(instance.manifest.templateOrigin.inputs[0].source.logicalId, expected.selected.dependency(expected.task, 'data').document.logicalId)
    assert.equal(target.host.artifacts.size, 1); assert.equal(original.host.artifacts.size, 0)
  })
  await t.test('provider restrictions and source/preflight failures cannot return a saved receipt', async () => {
    const f = await executionFixture(db)
    await assert.rejects(f.execution.instantiate(f.context, f.request(), ['postgres']), /PROVIDER_REQUIRED/)
    assert.equal(f.jobs.size, 0)
    const pending = await f.execution.instantiate(f.context, f.request())
    f.host.calls.invalidHtml = true
    await assert.rejects(f.run(pending), /PREFLIGHT_FAILED/)
    const result = await f.execution.status(f.context, pending.executionId)
    assert.equal(result.state, 'failed'); assert.equal(result.dashboard, undefined); assert.equal(f.host.artifacts.size, 0)
    f.host.calls.denied = true
    await assert.rejects(f.execution.instantiate(f.context, f.request()), /SOURCE_ACCESS_REVOKED/)
  })
  await t.test('explicit mappings reject missing fields, type/grain mismatches and stale dataset revisions', async () => {
    const f = await executionFixture(db), input = f.request(), resolved = await f.resolution.template(f.context, input)
    const selected = resolved.inputs[0], slot = resolved.template.content.inputSlots[0]
    await assert.rejects(f.bindings.bind(f.context, { ...selected, mapping: {} }, slot, randomUUID()), /TYPE_MISMATCH/)
    await assert.rejects(f.bindings.bind(f.context, { ...selected, mapping: { ...selected.mapping, month: 'revenue' } }, slot, randomUUID()), /TYPE_MISMATCH/)
    const bound = await f.bindings.bind(f.context, selected, slot, randomUUID())
    const id = randomUUID(); f.custom.set(id, { artifactId: id, revision: 2, definition: { binding: bound.binding, controls: {} } })
    await assert.rejects(f.bindings.bind(f.context, { ...selected, source: { type: 'dataset', artifactId: id, revision: 1 } }, slot, randomUUID()), /DATASET_CONFLICT/)
    const duplicateGrain = { ...slot, grain: ['revenue'] }
    await assert.rejects(f.bindings.bind(f.context, selected, duplicateGrain, randomUUID()), /GRAIN|grain/)
  })
  await t.test('execution capabilities fail explicitly when requirements cannot be verified', async () => {
    const f = await executionFixture(db)
    assert.equal((await f.resolution.availability(f.context, f.task.releaseId)).canPrepareTask, true)
    delete f.runtime.capabilities['platform.analytics']
    const result = await f.resolution.availability(f.context, f.task.releaseId)
    assert.equal(result.canPrepareTask, false); assert.deepEqual(result.reasons, ['LIBRARY_RUNTIME_CAPABILITY_REQUIRED'])
  })
  await t.test('Agent tool passes final-provider policy and exposes pending work to the wait loop', async () => {
    const f = await executionFixture(db)
    const middleware = new DashboardMiddleware(f.host.service, f.saves, f.execution).createMiddleware({ allowedFinalProviders: ['file.table'] },
      { ...f.context, xpertId: f.context.hostId })
    const tool = middleware.tools.find(item => item.name === 'dashboard_instantiate_template')
    assert.ok(tool)
    const result = JSON.parse(await tool.invoke(f.request()))
    assert.equal(result.state, 'queued'); assert.equal(result.nextAction, 'wait')
    await f.run(result)
    const saved = await f.execution.status(f.context, result.executionId)
    assert.equal(saved.dashboard.status, 'draft')
  })
})
