const catalogs: Record<SupportedLocale, Record<MessageKey, string>> = {
  'en-US': enUS,
  'zh-Hans': zhHans,
  'zh-Hant': zhHant
}

export function normalizeLocale(value?: string | null): SupportedLocale {
  const normalized = value?.replace('_', '-').toLowerCase() ?? ''
  if (
    normalized === 'zh-hant' ||
    normalized === 'zh-tw' ||
    normalized === 'zh-hk'
  ) {
    return 'zh-Hant'
  }
  if (
    normalized === 'zh-hans' ||
    normalized === 'zh-cn' ||
    normalized === 'zh-sg' ||
    normalized === 'zh'
  ) {
    return 'zh-Hans'
  }
  return 'en-US'
}

export function createTranslator(locale?: string | null) {
  const catalog = catalogs[normalizeLocale(locale)]
  return (
    key: MessageKey,
    values: Record<string, string | number> = {}
  ) =>
    Object.entries(values).reduce(
      (message, [name, value]) =>
        message.replaceAll(`{${name}}`, String(value)),
      catalog[key] ?? enUS[key]
    )
}
