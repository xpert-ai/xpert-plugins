export const RESUME_MATCHING_FIELD_RULES = [
  '## 其他字段写法',
  '',
  '- `matchedPoints`：每一条写成「【A/B/C/D 维度】结论 —— 证据：简历中的原文片段或事实」。至少要有一条。',
  '- `missingRequirements`：每一条写成「未满足项 —— 说明：为什么算不满足，或证据不足在哪里」。没有缺失项时返回空数组，不要用「暂未发现明显缺失项」之类的空话填充。',
  '- `riskFlags`：每一条写成「风险名（-N）：具体事实」，N 与 D 维度的扣分一致。没有风险时返回空数组。',
  '- `interviewQuestions`：3 到 5 条。必须针对缺失项和风险点设计，是能在面试中验证真伪的问题，不要写「请介绍你的项目」这类通用问题。'
].join('\n')

export const RESUME_MATCHING_TOOL_INSTRUCTION = [
  '## 输出要求',
  '',
  '把评分结果通过 `resume_screening_save_match_result` 工具保存，必须携带 jobId 和 candidateId。',
  '分数必须是 0 到 100 之间的数字；推荐值只能是 interview、hold 或 reject。'
].join('\n')

export const RESUME_MATCHING_JSON_INSTRUCTION = [
  '## 输出要求',
  '',
  '只输出一个 JSON 对象。不要输出 markdown 代码块，不要输出任何解释文字。',
  '字段为：score（数字）、recommendation（字符串）、matchedPoints（字符串数组）、missingRequirements（字符串数组）、riskFlags（字符串数组）、interviewQuestions（字符串数组）、reason（字符串）。'
].join('\n')

export function buildResumeMatchingPrompt(
  input: ResumeMatchingPromptInput,
  options: ResumePromptOptions = {}
): string {
  const outputMode = options.outputMode ?? 'tool'
  return [
    RESUME_MATCHING_SYSTEM_PROMPT,
    '',
    '## 本次评分上下文',
    '',
    describeJobCriteria(input.job),
    '',
    describeCandidate(input.candidate),
    '',
    '## 已抽取的结构化事实',
    '',
    input.extracted
      ? JSON.stringify(input.extracted, null, 2)
      : '（未提供结构化抽取结果，请直接依据简历原文判断。）',
    '',
    RESUME_MATCHING_FIELD_RULES,
    '',
    RESUME_MATCHING_REASON_CONTRACT,
    '',
    outputMode === 'json' ? RESUME_MATCHING_JSON_INSTRUCTION : RESUME_MATCHING_TOOL_INSTRUCTION
  ].join('\n')
}
