export function resolveLocale(value?: string): SupportedLocale {
  const normalized = value?.replace('_', '-')
  if (normalized === 'zh-Hans' || normalized === 'zh-CN' || normalized === 'zh-SG') return 'zh-Hans'
  if (normalized === 'zh-Hant' || normalized === 'zh-TW' || normalized === 'zh-HK' || normalized === 'zh-MO') return 'zh-Hant'
  return 'en-US'
}

export function createI18n(locale: SupportedLocale) {
  const catalog = catalogs[locale]
  const t = (key: MessageKey, values?: Record<string, string | number>): string => {
    let message = catalog[key]
    for (const [name, value] of Object.entries(values ?? {})) {
      message = message.replaceAll(`{${name}}`, String(value))
    }
    return message
  }
  return {
    locale,
    t,
    stage(value: string): string {
      const key = stageKeys[value]
      return key ? t(key) : value
    },
    view(value: string): string {
      const key = viewKeys[value]
      return key ? t(key) : value
    },
    route(value: 'object' | 'character'): string {
      return t(value === 'character' ? 'characterRoute' : 'objectRoute')
    },
    status(value: string): string {
      const key = statusKeys[value]
      return key ? t(key) : value.replaceAll('_', ' ')
    },
    formatDate(value: string): string {
      return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(value))
    }
  }
}
