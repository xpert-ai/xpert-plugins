export function translator(locale: string) {
  const aliases = ['zh', 'zh-cn', 'zh-sg', 'zh-hans', 'zh_hans']
  const catalog = aliases.includes(locale.toLowerCase()) ? zh : en
  return (key: string) =>
    key in catalog ? catalog[key as Key] : catalog.model_failed
}
