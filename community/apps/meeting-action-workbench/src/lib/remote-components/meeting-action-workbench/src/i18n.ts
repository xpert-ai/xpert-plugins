export function resolveLocale(locale?: string): Locale {
  const normalized = locale?.replace('_', '-').toLowerCase()
  if (normalized === 'zh-hans' || normalized === 'zh-cn' || normalized === 'zh-sg') return 'zh-Hans'
  return 'en-US'
}

export function formatDate(locale: Locale, value: string) {
  return new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(new Date(value))
}
