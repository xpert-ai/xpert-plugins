export type MessageKey = keyof Messages
export type Locale = 'en-US' | 'zh-Hans'
export function normalizeLocale(value?: string): Locale {
  return ['zh-Hans', 'zh_Hans', 'zh-CN', 'zh_CN', 'zh-SG'].includes(value ?? '')
    ? 'zh-Hans'
    : 'en-US'
}
export function createI18n(locale: Locale) {
  const messages = locale === 'zh-Hans' ? zh : en
  return {
    locale,
    t: (key: MessageKey) => messages[key],
    number: (v: number) => new Intl.NumberFormat(locale).format(v),
    currency: (v: number) =>
      new Intl.NumberFormat(locale, {
        style: 'currency',
        currency: 'CNY',
        maximumFractionDigits: 0,
      }).format(v),
    date: (v: string) =>
      new Intl.DateTimeFormat(locale, {
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
      }).format(new Date(v)),
  }
}
