export type Locale = 'en-US' | 'zh-Hans'
const aliases: Record<string, Locale> = { en: 'en-US', 'en-US': 'en-US', 'en-GB': 'en-US', zh: 'zh-Hans', 'zh-Hans': 'zh-Hans', 'zh-CN': 'zh-Hans', 'zh-SG': 'zh-Hans' }
export function normalizeLocale(value = 'en-US'): Locale { return aliases[value.replaceAll('_', '-')] ?? 'en-US' }
export function createI18n(locale: Locale) {
  const catalog = locale === 'zh-Hans' ? zh : en
  return {
    locale,
    t: (key: MessageKey, values: Record<string, string | number> = {}) => catalog[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`)),
    date: (value: string) => new Intl.DateTimeFormat(locale, { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(new Date(value)),
    number: (value: number) => new Intl.NumberFormat(locale).format(value),
    plural: (value: number) => new Intl.PluralRules(locale).select(value),
  }
}
export const I18nContext = createContext(createI18n('en-US'))
export const useI18n = () => useContext(I18nContext)
